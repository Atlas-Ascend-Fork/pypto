static std::string GetExpandBinOpSuffix(int opType)
{
    switch (opType) {
        case 0:
            return "ADD";
        case 1:
            return "SUB";
        case 2:
            return "MUL";
        case 3:
            return "DIV";
        case 4:
            return "MAX";
        case 5:
            return "MIN";
        default:
            PRO_CODEGEN_CHECK(ExternalError::NOT_IMPLEMENTED_ERROR, false)
                << "Unsupported expand binop op_type: " << opType;
            return "ADD";
    }
}

